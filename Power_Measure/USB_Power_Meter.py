"""
USB POWER METER DATA LOGGER
===========================

Device:
    Atorch UD18 USB Power Meter
    Bluetooth/Serial version: UD18_SPP

Purpose:
    This program reads measurement data from the Atorch UD18 USB power meter
    through a serial connection and displays the following values:

        - Voltage (V)
        - Current (A)
        - Power (W)
        - Capacity (mAh)
        - Energy (Wh)
        - USB D- Voltage
        - USB D+ Voltage
        - Temperature
        - Elapsed Measurement Time

Recommended Hardware:
    Atorch UD18 USB Power Meter with Bluetooth/SPP communication.

Computer:
    macOS

Python Requirements:
    Python 3
    pyserial

Install pyserial:
    python3 -m pip install pyserial

Typical Serial Port:
    /dev/cu.UD18_SPP-JL_SPP

Serial Settings:
    Baud Rate : 115200
    Data Bits : 8
    Parity    : None
    Stop Bits : 1

How to Run:
    1. Connect the UD18 meter to the computer.
    2. Establish the Bluetooth/serial connection.
    3. Verify the serial port name.
    4. Run this Python program.
    5. Press Ctrl+C to stop data collection.

Notes:
    - The program continuously receives binary packets from the UD18.
    - Measurement data are decoded from the received packets.
    - Elapsed time is generated by Python and starts when the program begins.

Author:
    Farid Farahmand

Project:
    InSee USB Power Measurement

IMPORTANT: 
    - This program was tested on MAC using COOLTERM only. PLease report any iossues. 

------------------------------------------------------------
"""
import serial
import time

# --------------------------------------------------
# Serial settings
# --------------------------------------------------

PORT = "/dev/cu.UD18_SPP-JL_SPP"
BAUD = 115200

ser = serial.Serial(
    port=PORT,
    baudrate=BAUD,
    bytesize=8,
    parity="N",
    stopbits=1,
    timeout=2
)


# --------------------------------------------------
# Find one complete UD18 packet
# --------------------------------------------------

def find_packet():

    while True:

        b = ser.read(1)

        if not b:
            continue

        # Look for first header byte: FF
        if b[0] == 0xFF:

            b2 = ser.read(1)

            # Look for second header byte: 55
            if b2 and b2[0] == 0x55:

                # Packet is 36 bytes total.
                # We already received FF 55, so read 34 more.
                remaining = ser.read(34)

                if len(remaining) == 34:

                    return bytes([0xFF, 0x55]) + remaining


# --------------------------------------------------
# Print table header
# --------------------------------------------------

print()
print(
    f"{'Voltage(V)':>10} "
    f"{'Current(A)':>10} "
    f"{'Power(W)':>10} "
    f"{'Capacity(mAh)':>14} "
    f"{'Energy(Wh)':>12} "
    f"{'D-(V)':>8} "
    f"{'D+(V)':>8} "
    f"{'Temp(C)':>8} "
    f"{'Elapsed Time':>14}"
)

print("-" * 112)


# --------------------------------------------------
# Start Python timer
# --------------------------------------------------

start_time = time.monotonic()

last_print_time = -1


# --------------------------------------------------
# Main loop
# --------------------------------------------------

try:

    while True:

        packet = find_packet()

        # Measurement packet
        if packet[2] != 0x01:
            continue

        # ------------------------------------------
        # Decode UD18 data
        # ------------------------------------------

        voltage = int.from_bytes(
            packet[4:7],
            byteorder="big"
        ) / 100.0

        current = int.from_bytes(
            packet[7:10],
            byteorder="big"
        ) / 100.0

        power = voltage * current

        capacity_mAh = int.from_bytes(
            packet[10:13],
            byteorder="big"
        )

        energy_Wh = int.from_bytes(
            packet[13:17],
            byteorder="big"
        ) / 100.0

        d_minus = int.from_bytes(
            packet[17:19],
            byteorder="big"
        ) / 100.0

        d_plus = int.from_bytes(
            packet[19:21],
            byteorder="big"
        ) / 100.0

        temperature = packet[22]

        # ------------------------------------------
        # Python elapsed time
        # ------------------------------------------

        elapsed = int(time.monotonic() - start_time)

        hours = elapsed // 3600
        minutes = (elapsed % 3600) // 60
        seconds = elapsed % 60

        time_string = (
            f"{hours:03d}:"
            f"{minutes:02d}:"
            f"{seconds:02d}"
        )

        # ------------------------------------------
        # Print only ONE row per second
        # ------------------------------------------

        if elapsed != last_print_time:

            print(
                f"{voltage:10.2f} "
                f"{current:10.2f} "
                f"{power:10.2f} "
                f"{capacity_mAh:14d} "
                f"{energy_Wh:12.2f} "
                f"{d_minus:8.2f} "
                f"{d_plus:8.2f} "
                f"{temperature:8d} "
                f"{time_string:>14}"
            )

            last_print_time = elapsed


# --------------------------------------------------
# Stop with Ctrl+C
# --------------------------------------------------

except KeyboardInterrupt:

    print("\nMeasurement stopped.")


finally:

    ser.close()
    print("Serial port closed.")
